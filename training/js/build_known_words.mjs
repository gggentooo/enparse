/**
 * training/js/build_known_words.mjs — subword known-word list from NGSL (T41)
 *
 * Description:
 *   Downloads the pinned NGSL 1.2 research file (configs/dictionary.yaml) into
 *   data/raw/ngsl/ if missing, checks its SHA-256, and writes every headword and
 *   word form (lower case, unique, sorted) to the app's
 *   src/modules/subword/knownWords.generated.ts with the source, license, and
 *   attribution (CC BY-SA 4.0). subwordParser.ts accepts an affix split only if
 *   the remaining base is in this list (or is the word's wink lemma).
 *
 * Run (from training/js): npm run known-words
 * Dependencies: js-yaml; Node fetch and crypto. Network: one dev-time download.
 * Status: implemented (T41).
 */

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as yaml from "js-yaml";

const HERE = dirname(fileURLToPath(import.meta.url));
const TRAINING = resolve(HERE, "..");
const cfg = yaml.load(readFileSync(join(TRAINING, "configs", "dictionary.yaml"), "utf8"));
const src = cfg.sources.ngsl;
const file = join(TRAINING, src.file);

if (!existsSync(file)) {
  mkdirSync(dirname(file), { recursive: true });
  const res = await fetch(src.url);
  if (!res.ok) throw new Error(`download failed: HTTP ${res.status}`);
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
}
const bytes = readFileSync(file);
const sha = createHash("sha256").update(bytes).digest("hex");
if (sha !== src.sha256) throw new Error(`SHA-256 mismatch for ${src.file}: ${sha}`);

const words = new Set();
let headwords = 0;
for (const line of bytes.toString("utf8").split(/\r?\n/)) {
  if (!line.trim() || line.startsWith("#")) continue;
  const forms = line.split(",").map((w) => w.trim().toLowerCase()).filter((w) => /^[a-z][a-z'-]*$/.test(w));
  if (forms.length) headwords++;
  for (const w of forms) words.add(w);
}
const sorted = [...words].sort();
const out = resolve(TRAINING, cfg.known_words.output); // relative to training/
const ts = `/**
 * src/modules/subword/knownWords.generated.ts — known-word list for affix splits (generated; do not edit)
 *
 * Generated by training/js/build_known_words.mjs (npm run known-words) from:
 *   ${src.name}
 *   ${src.url} (SHA-256 ${src.sha256})
 * ${headwords} headwords, ${sorted.length} distinct forms (lower case).
 *
 * License: ${src.license} (${src.license_url}). Attribution: ${src.attribution}
 * Changes: lower-cased, de-duplicated, and sorted; comment lines removed.
 */

/** Source and license, shown on the About page. */
export const KNOWN_WORDS_SOURCE = ${JSON.stringify({ name: src.name, url: src.url, license: src.license, attribution: src.attribution })} as const;

/** Newline-separated known words (one string keeps the bundle small). */
export const KNOWN_WORDS = ${JSON.stringify(sorted.join("\n"))};
`;
writeFileSync(out, ts);
console.log(`${headwords} headwords, ${sorted.length} forms -> ${out}`);
