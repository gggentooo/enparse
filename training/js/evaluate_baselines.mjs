/**
 * training/js/evaluate_baselines.mjs — accuracy of the JS baseline taggers
 *
 * Description:
 *   Sets the bar the trained model must beat. Runs wink-nlp (POS tags only)
 *   and compromise (POS tags and chunks) on EWT dev and test, using the
 *   Phase 3 word segmentation, and reports UPOS accuracy (both) and chunk F1
 *   (compromise). There is no rule-based chunker for wink-nlp (the app has
 *   no fallback mode).
 *
 * Phase: 5 — Baseline evaluation.
 * Run with (from training/js): npm run baselines   (= tsx evaluate_baselines.mjs)
 *
 * Method (details in lib/baselines.mjs):
 *   - Gold: data/processed/aligned/<split>.jsonl (runtime words with UPOS and
 *     BIO chunk tags). All EWT words are reviewed, so every sentence counts
 *     for chunk F1.
 *   - Each baseline gets the sentence's words joined by single spaces; its
 *     tokens are mapped back to the words by character offset.
 *   - Metrics: UPOS accuracy (overall, per tag); chunk P/R/F1 (overall, per
 *     type) with seqeval-equivalent span matching (lib/metrics.mjs).
 *   - Structure output: no baseline (neither library has a dependency parser).
 *
 * Dependencies:
 *   Node:   wink-nlp, wink-eng-lite-web-model, compromise, js-yaml;
 *           ./lib/baselines.mjs, ./lib/metrics.mjs.
 *   Reads:  ../configs/data.yaml (paths.aligned, baselines.*); data/processed/aligned/;
 *           ./package-lock.json (versions for the report).
 *   Writes: ../reports/baselines.md.
 *
 * Status: implemented (Phase 5).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import nlpCompromise from "compromise";
import * as yaml from "js-yaml";
import winkModel from "wink-eng-lite-web-model";
import winkNLP from "wink-nlp";
import { COMPROMISE_UPOS, COORDINATORS, compromiseTags, winkUpos } from "./lib/baselines.mjs";
import { chunkScores, uposScores } from "./lib/metrics.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const TRAINING = resolve(HERE, "..");
const CHUNK_TYPES = ["NP", "VP", "PP", "ADJP", "ADVP"];

function lockVersions() {
  const lock = JSON.parse(readFileSync(join(HERE, "package-lock.json"), "utf8"));
  const v = (n) => lock.packages[`node_modules/${n}`]?.version ?? "?";
  return { wink: v("wink-nlp"), model: v("wink-eng-lite-web-model"), compromise: v("compromise") };
}

function loadSplit(path) {
  return readFileSync(path, "utf8")
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l));
}

function evaluateSplit(sentences, wink) {
  const gold = { upos: [], chunk: [] };
  const pred = { wink: [], compUpos: [], compChunk: [] };
  const t0 = performance.now();
  for (const s of sentences) {
    const words = s.words.map((w) => w.form);
    gold.upos.push(...s.words.map((w) => w.upos));
    gold.chunk.push(s.words.map((w) => w.chunk));
    pred.wink.push(...winkUpos(wink, words));
  }
  const t1 = performance.now();
  for (const s of sentences) {
    const { upos, chunk } = compromiseTags(nlpCompromise, s.words.map((w) => w.form));
    pred.compUpos.push(...upos);
    pred.compChunk.push(chunk);
  }
  const t2 = performance.now();
  return {
    sentences: sentences.length,
    words: gold.upos.length,
    wink: { upos: uposScores(gold.upos, pred.wink), seconds: (t1 - t0) / 1000 },
    compromise: {
      upos: uposScores(gold.upos, pred.compUpos),
      chunks: chunkScores(gold.chunk, pred.compChunk),
      seconds: (t2 - t1) / 1000,
    },
  };
}

const pct = (x) => `${(100 * x).toFixed(2)}%`;
const num = (n) => n.toLocaleString("en-US");

function writeReport(path, cfg, results, topN) {
  const v = lockVersions();
  const splits = [...results.keys()];
  const L = [];
  L.push("# Baselines (Phase 5)", "");
  L.push(
    `Generated by \`js/evaluate_baselines.mjs\` on UD English EWT ${cfg.ud_ewt.release_tag} (Phase 3 aligned words). ` +
      `wink-nlp ${v.wink} + wink-eng-lite-web-model ${v.model}; compromise ${v.compromise}.`,
    "",
    "Method: each library gets the runtime words joined by single spaces and its tokens are mapped back to the words " +
      "by offset (`js/lib/baselines.mjs`). wink-nlp has no chunker (the app has no fallback mode), so it has UPOS only. " +
      "Chunk F1 is span-level, seqeval-equivalent. The structure output (heads) has no baseline.",
    "",
  );
  L.push("## Summary", "");
  L.push("| Split | Words | wink-nlp UPOS | compromise UPOS | compromise chunk F1 (P / R) |");
  L.push("|---|---|---|---|---|");
  for (const [split, r] of results) {
    const c = r.compromise.chunks.overall;
    L.push(
      `| ${split} | ${num(r.words)} | **${pct(r.wink.upos.accuracy)}** | **${pct(r.compromise.upos.accuracy)}** | ` +
        `**${pct(c.f1)}** (${pct(c.precision)} / ${pct(c.recall)}) |`,
    );
  }
  L.push("", "Bar for Phase 7 (test split): UPOS above the better of the two baselines; chunk F1 above compromise.", "");

  L.push("## Chunk F1 per type (compromise)", "");
  L.push("| Type | " + splits.map((s) => `${s} F1 (P / R)`).join(" | ") + " | Gold chunks (" + splits.join(" / ") + ") |");
  L.push("|---|" + splits.map(() => "---").join("|") + "|---|");
  for (const t of CHUNK_TYPES) {
    const cells = splits.map((s) => {
      const x = results.get(s).compromise.chunks.perType[t];
      return x ? `${pct(x.f1)} (${pct(x.precision)} / ${pct(x.recall)})` : "—";
    });
    const golds = splits.map((s) => num(results.get(s).compromise.chunks.perType[t]?.gold ?? 0)).join(" / ");
    L.push(`| ${t} | ${cells.join(" | ")} | ${golds} |`);
  }
  L.push("", "ADVP and ADJP are rarely predicted: compromise has no ADVP chunk type, and adverbs fall inside its verb chunks.", "");

  L.push("## UPOS accuracy per tag", "");
  const tags = Object.keys(results.get(splits[0]).wink.upos.perTag).sort();
  L.push("| Gold tag | " + splits.map((s) => `${s} words`).join(" | ") + " | " + splits.map((s) => `wink ${s}`).join(" | ") + " | " + splits.map((s) => `compromise ${s}`).join(" | ") + " |");
  L.push("|---|" + splits.map(() => "---").join("|") + "|" + splits.map(() => "---").join("|") + "|" + splits.map(() => "---").join("|") + "|");
  for (const t of tags) {
    const n = splits.map((s) => num(results.get(s).wink.upos.perTag[t]?.total ?? 0));
    const w = splits.map((s) => pct(results.get(s).wink.upos.perTag[t]?.accuracy ?? 0));
    const c = splits.map((s) => pct(results.get(s).compromise.upos.perTag[t]?.accuracy ?? 0));
    L.push(`| ${t} | ${n.join(" | ")} | ${w.join(" | ")} | ${c.join(" | ")} |`);
  }
  L.push(
    "",
    "`X` includes split-word pieces (`goeswith`, Phase 3), which neither library can tag as X. " +
      "compromise's tag set lacks some UD distinctions, which lowers its UPOS score: possessive pronouns are " +
      "`Noun/Possessive` (`my` → NOUN), `be`/`have`/`do` as auxiliaries are often plain `Verb` (→ VERB), and " +
      "indefinite pronouns are nouns (`something`). No word-specific rules were added for these.",
    "",
  );

  L.push(`## Most frequent UPOS errors (${splits[0]})`, "");
  const dev = results.get(splits[0]);
  L.push(`- wink-nlp: ${dev.wink.upos.confusions.slice(0, topN).map(([k, n]) => `${k} (${n})`).join(", ")}`);
  L.push(`- compromise: ${dev.compromise.upos.confusions.slice(0, topN).map(([k, n]) => `${k} (${n})`).join(", ")}`);
  L.push("", "## compromise tag mapping", "");
  L.push("Tokens without letters or digits → PUNCT (SYM for `$ % & + < = > @ # ^ | ~ € £ ¥`), whatever compromise tagged them. " +
    `\`Conjunction\` → CCONJ for ${[...COORDINATORS].map((c) => `\`${c}\``).join(", ")}, PART for \`to\` (compromise's infinitive marker), else SCONJ. ` +
    "Then the first matching compromise tag wins: " + COMPROMISE_UPOS.map(([a, b]) => `\`${a}\`→${b}`).join(", ") + "; anything else → X. " +
    "Chunks: compromise `Noun`→NP, `Verb`→VP, `Adjective`→ADJP; prepositions → single-word PP; punctuation, conjunctions, symbols → O.", "");
  L.push("## Run time", "");
  for (const [split, r] of results) L.push(`- ${split}: wink-nlp ${r.wink.seconds.toFixed(1)} s, compromise ${r.compromise.seconds.toFixed(1)} s (Node, single thread).`);
  L.push("");
  writeFileSync(path, L.join("\n"), "utf8");
}

function main() {
  const cfg = yaml.load(readFileSync(join(TRAINING, "configs", "data.yaml"), "utf8"));
  const { splits, report, top_confusions: topN } = cfg.baselines;
  const wink = winkNLP(winkModel);
  const results = new Map();
  for (const split of splits) {
    const sentences = loadSplit(join(TRAINING, cfg.paths.aligned, `${split}.jsonl`));
    const r = evaluateSplit(sentences, wink);
    results.set(split, r);
    console.log(
      `${split}: wink UPOS ${pct(r.wink.upos.accuracy)} | compromise UPOS ${pct(r.compromise.upos.accuracy)}, ` +
        `chunk F1 ${pct(r.compromise.chunks.overall.f1)}`,
    );
  }
  writeReport(join(TRAINING, report), cfg, results, topN);
  console.log(`report -> training/${report}`);
}

main();
