/**
 * training/js/error_analysis.mjs — Phase 7 error analysis → reports/errors.md
 *
 * Description:
 *   For each model's carried-forward checkpoint (configs/eval.yaml →
 *   phase7_checkpoints: stage per model; the stage record's selected_run),
 *   reads the test predictions, decodes trees with the app's treeDecoder.ts
 *   (via tsx, same as nested_eval.mjs), finds every error unit
 *   (lib/errors.mjs), and writes:
 *     - full test-set counts by area and type (all errors, not a sample),
 *     - nested-view bracket misses by cause (attachment vs label only),
 *     - attachment errors shared by all models (hard cases),
 *     - a seeded sample of 100 errors per model, grouped by type, with examples.
 *   The full sample per model goes to data/eval/<model>/<run>/<split>_errors.jsonl.
 *
 * Phase: 7 task 5. Run (from training/js): npx tsx error_analysis.mjs
 *
 * Dependencies:
 *   Node: tsx, js-yaml; ./lib/errors.mjs; app code: src/modules/parser/treeDecoder.ts.
 *   Reads: ../configs/data.yaml (paths.eval), ../configs/eval.yaml (phase7_checkpoints,
 *          phase7_stages, error_analysis); data/eval/<model>/{phase7,phase7_extended}.json;
 *          <split>_predictions.jsonl.
 *   Writes: ../reports/errors.md; <split>_errors.jsonl per run.
 *
 * Status: implemented (Phase 7).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as yaml from "js-yaml";
import { displayTree } from "../../src/modules/parser/quantifiers.ts";
import { buildPhrases, decodeArcTree, decodeTree, phraseSpans } from "../../src/modules/parser/treeDecoder.ts";
import { bracketCauses, context, sample, sentenceErrors } from "./lib/errors.mjs";
import { decodeRecord } from "./lib/nested.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const TRAINING = resolve(HERE, "..");
const dataCfg = yaml.load(readFileSync(join(TRAINING, "configs", "data.yaml"), "utf8"));
const evalCfg = yaml.load(readFileSync(join(TRAINING, "configs", "eval.yaml"), "utf8"));
const ea = evalCfg.error_analysis;
const evalDir = join(TRAINING, dataCfg.paths.eval);
const decoder = { buildPhrases, phraseSpans, displayTree };
const AREAS = ["upos", "chunk", "head", "relation"];
const AREA_NAME = { upos: "UPOS", chunk: "Chunk", head: "Attachment (head)", relation: "Relation (head right)" };
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) : "—");

const models = Object.entries(evalCfg.phase7_checkpoints).map(([model, stage]) => {
  const recordFile = stage === "base" ? "phase7.json" : evalCfg.phase7_stages[stage].record;
  const record = JSON.parse(readFileSync(join(evalDir, model, recordFile), "utf8"));
  const run = record.selected_run;
  const dir = join(evalDir, model, run);
  const records = readFileSync(join(dir, `${ea.split}_predictions.jsonl`), "utf8")
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l));
  const errors = [];
  const brackets = { gold: 0, missed: 0, inside: 0, intruder: 0, labelOnly: 0, other: 0 };
  const headErrors = new Set();
  let repairedWrong = 0;
  let words = 0;
  for (const r of records) {
    const tree = decodeRecord(r, { decodeTree, decodeArcTree });
    words += r.words.length;
    for (const e of sentenceErrors(r, tree)) {
      errors.push({ ...e, sent_id: r.sent_id, text: context(r.words, e.start, e.end) });
      if (e.area === "head") headErrors.add(`${r.sent_id}#${e.start}`);
    }
    const repaired = new Set(tree.repairedWords);
    tree.heads.forEach((h, i) => {
      if (h !== r.gold_head[i] && repaired.has(i)) repairedWrong++;
    });
    const b = bracketCauses(r, tree, decoder);
    for (const k of Object.keys(brackets)) brackets[k] += b[k];
  }
  const picked = sample(errors, ea.sample_size, ea.seed);
  writeFileSync(join(dir, `${ea.split}_errors.jsonl`), picked.map((e) => JSON.stringify(e)).join("\n") + "\n");
  return { model, stage, run, sentences: records.length, words, errors, picked, brackets, headErrors, repairedWrong };
});

function countBy(items, key) {
  const m = new Map();
  for (const x of items) m.set(key(x), (m.get(key(x)) ?? 0) + 1);
  return m;
}

const lines = [];
const out = (s = "") => lines.push(s);
out("# Error analysis (Phase 7 task 5)");
out();
out(
  "Generated by `js/error_analysis.mjs` (from `training/js`: `npx tsx error_analysis.mjs`). " +
    `Split: ${ea.split}. Trees are decoded with the app's \`treeDecoder.ts\` (what the nested view shows). ` +
    "An error unit is one wrong UPOS tag, one gold chunk not predicted exactly (or a predicted chunk overlapping no gold chunk; " +
    "spans read like seqeval's default mode), one word with the wrong head, or one word with the right head but the wrong relation. " +
    "Relations are compared without subtypes (the current group B strips them).",
);
out();
out("## Checkpoints (owner, 2026-11-20; `configs/eval.yaml` → `phase7_checkpoints`)");
out();
out("| Model | Stage | Run (dev-selected seed) | Sentences | Words |");
out("|---|---|---|---|---|");
for (const m of models) out(`| ${m.model} | ${m.stage} | \`${m.run}\` | ${m.sentences} | ${m.words} |`);
out();
out("## All errors on the test split, by area");
out();
out(`| Model | ${AREAS.map((a) => AREA_NAME[a]).join(" | ")} | Total |`);
out(`|---|${AREAS.map(() => "---").join("|")}|---|`);
for (const m of models) {
  const c = countBy(m.errors, (e) => e.area);
  out(`| ${m.model} | ${AREAS.map((a) => c.get(a) ?? 0).join(" | ")} | ${m.errors.length} |`);
}
out();

for (const area of AREAS) {
  const all = new Map();
  for (const m of models) for (const [k, v] of countBy(m.errors.filter((e) => e.area === area), (e) => e.type)) all.set(k, (all.get(k) ?? 0) + v);
  let types = [...all.entries()].sort((a, b) => b[1] - a[1]).map(([k]) => k);
  const limit = area === "relation" ? 12 : area === "chunk" ? 14 : types.length;
  const rest = types.slice(limit);
  types = types.slice(0, limit);
  out(`### ${AREA_NAME[area]} errors by type (count, % of the model's ${area} errors)`);
  out();
  out(`| Type | ${models.map((m) => m.model).join(" | ")} |`);
  out(`|---|${models.map(() => "---").join("|")}|`);
  const rows = rest.length ? [...types, "(other types)"] : types;
  for (const t of rows) {
    const cells = models.map((m) => {
      const errs = m.errors.filter((e) => e.area === area);
      const n = t === "(other types)" ? errs.filter((e) => rest.includes(e.type)).length : errs.filter((e) => e.type === t).length;
      return `${n} (${pct(n, errs.length)})`;
    });
    out(`| ${t} | ${cells.join(" | ")} |`);
  }
  out();
}

out("## Nested view: missed multi-word brackets by cause");
out();
out(
  "A gold multi-word bracket (type, start, end) with no identical predicted bracket, by the first cause that applies. " +
    "*Head error inside*: a non-punctuation word inside the span has the wrong head. *Outside word attached in*: a word outside " +
    "the span wrongly attaches into it, so the predicted phrase grows. *Label only*: same span, other type (e.g. NP vs PP). " +
    "*Other*: punctuation or UPOS differences.",
);
out();
out("| Model | Gold brackets | Missed | Head error inside | Outside word attached in | Label only | Other |");
out("|---|---|---|---|---|---|---|");
for (const { model, brackets: b } of models)
  out(
    `| ${model} | ${b.gold} | ${b.missed} (${pct(b.missed, b.gold)}%) | ${b.inside} (${pct(b.inside, b.missed)}%) | ` +
      `${b.intruder} (${pct(b.intruder, b.missed)}%) | ${b.labelOnly} (${pct(b.labelOnly, b.missed)}%) | ${b.other} (${pct(b.other, b.missed)}%) |`,
  );
out();
const perError = models.map((m) => `${m.model} ${(m.brackets.missed / Math.max(1, [...m.headErrors].length)).toFixed(2)}`);
out(`Missed multi-word brackets per attachment error (all words): ${perError.join("; ")}.`);
out();

out("## Hard cases: attachment errors shared by all models");
out();
const shared = [...models[0].headErrors].filter((k) => models.every((m) => m.headErrors.has(k)));
out("| Model | Head errors | Shared by all four |");
out("|---|---|---|");
for (const m of models) out(`| ${m.model} | ${m.headErrors.size} | ${shared.length} (${pct(shared.length, m.headErrors.size)}%) |`);
out();
const sharedTypes = countBy(
  models[0].errors.filter((e) => e.area === "head" && shared.includes(`${e.sent_id}#${e.start}`)),
  (e) => e.type,
);
out("Shared errors by type: " + [...sharedTypes.entries()].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join("; ") + ".");
out();

out("## Attachment errors from tree repair");
out();
out(
  "Words whose head did not come from their top group B candidate (`treeDecoder.ts` repair: root, cycle, or unresolvable head). " +
    "The planned biaffine head with MST decoding replaces this step.",
);
out();
out("| Model | Head errors | On repaired words |");
out("|---|---|---|");
for (const m of models) out(`| ${m.model} | ${m.headErrors.size} | ${m.repairedWrong} (${pct(m.repairedWrong, m.headErrors.size)}%) |`);
out();
out(`## Sample of ${ea.sample_size} errors per model, grouped by type`);
out();
out(
  `Seeded sample (seed ${ea.seed}) over all error units of the model, so areas appear in proportion to their counts above. ` +
    `${ea.examples_per_group} examples per group; ⟦…⟧ marks the error. Full samples: \`data/eval/<model>/<run>/${ea.split}_errors.jsonl\`.`,
);
out();
for (const m of models) {
  out(`### ${m.model} (\`${m.run}\`)`);
  out();
  out("| Area | Type | Count | Examples |");
  out("|---|---|---|---|");
  const groups = new Map();
  for (const e of m.picked) {
    const k = `${e.area}\u0000${e.type}`;
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(e);
  }
  const sorted = [...groups.entries()].sort((a, b) => AREAS.indexOf(a[1][0].area) - AREAS.indexOf(b[1][0].area) || b[1].length - a[1].length);
  for (const [, es] of sorted) {
    const ex = es
      .slice(0, ea.examples_per_group)
      .map((e) => {
        const gp = e.gold !== undefined ? ` (gold ${e.gold}; pred ${e.pred})` : "";
        return `${e.text}${gp}`.replaceAll("|", "\\|");
      })
      .join("<br>");
    out(`| ${AREA_NAME[es[0].area]} | ${es[0].type} | ${es.length} | ${ex} |`);
  }
  out();
}

writeFileSync(join(TRAINING, "reports", "errors.md"), lines.join("\n"));
for (const m of models) console.log(`${m.model}/${m.run}: ${m.errors.length} error units, sample ${m.picked.length}`);
console.log("done -> reports/errors.md");
