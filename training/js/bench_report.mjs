/**
 * training/js/bench_report.mjs — reports/benchmark.md from the Phase 10 results
 *
 * Description:
 *   Reads data/bench/phase10_<browsers>.json and spike_<browsers>.json
 *   (bench_browsers.mjs) and writes reports/benchmark.md: load and parse
 *   times, memory, budget check, download sizes, the T31 cache spike, and the
 *   parse times catalog.json carries per model.
 *
 * Catalog parse times (owner, 2026-11-23; T65): performance.parse_5000_chars_s
 *   = the slowest warm median across the full-speed browsers (chrome, safari)
 *   for `wasm` (int8, many threads) and `webgpu` (fp16); the two-core VM
 *   (vm-chrome) for `wasm_2core`; the slowest single-threaded run for
 *   `wasm_1thread`. No per-model memory requirement (owner, T65: the 4 GB VM
 *   ran both models; only the device-wide memory hint warns). Written to
 *   data/bench/catalog_performance.json for package_models.py (T66).
 *
 * Phase: 10 (T64). Run (from training/js): node bench_report.mjs
 * Dependencies: js-yaml; ../configs/eval.yaml (benchmark).
 * Status: implemented (Phase 10).
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as yaml from "js-yaml";

const HERE = dirname(fileURLToPath(import.meta.url));
const TRAINING = resolve(HERE, "..");
const BENCH = join(TRAINING, "data", "bench");
const cfg = yaml.load(readFileSync(join(TRAINING, "configs", "eval.yaml"), "utf8")).benchmark;
/** Runs on full-speed machines (many threads) vs the two-core VM (T67). */
export const TWO_CORE_BROWSERS = ["vm-chrome"];

const files = readdirSync(BENCH).filter((f) => /^(phase10|spike)_.*\.json$/.test(f));
const stRuns = readdirSync(BENCH)
  .filter((f) => /^phase10st_.*\.json$/.test(f))
  .flatMap((f) => JSON.parse(readFileSync(join(BENCH, f), "utf8")).results)
  .filter((r) => r.ok && r.phase === "warm");
const runs = files.flatMap((f) => JSON.parse(readFileSync(join(BENCH, f), "utf8")).results.map((r) => ({ ...r, file: f })));
const meta = JSON.parse(readFileSync(join(BENCH, files.find((f) => f.startsWith("phase10")) ?? files[0]), "utf8"));
const sizes = Object.fromEntries(meta.models.map((m) => [m.model, m.bytes]));

const bench = runs.filter((r) => r.mode === "bench" && r.ok);
const pair = (browser, model, variant) => ({
  cold: bench.find((r) => r.browser === browser && r.model === model && r.variant === variant && r.phase === "cold"),
  warm: bench.find((r) => r.browser === browser && r.model === model && r.variant === variant && r.phase === "warm"),
});
const browsers = [...new Set(bench.map((r) => r.browser))];
const models = [...new Set(bench.map((r) => r.model))];
const ms = (x) => (x === undefined || x === null ? "—" : `${Math.round(x).toLocaleString("en-US")}`);
const gb = (mb) => (mb === undefined || mb === null ? "—" : (mb / 1024).toFixed(2));
/** Browser name and version from the user agent (Edge before Chrome; Safari last). */
const version = (ua) => {
  const edge = /Edg\/([\d.]+)/.exec(ua);
  if (edge) return `Edge ${edge[1]}`;
  const chrome = /Chrome\/([\d.]+)/.exec(ua);
  if (chrome) return `Chrome ${chrome[1]}`;
  return `Safari ${/Version\/([\d.]+)/.exec(ua)?.[1] ?? "?"}`;
};
const os = (ua) => (/Windows NT/.test(ua) ? "Windows" : /Mac OS X/.test(ua) ? "macOS" : /Android/.test(ua) ? "Android" : /iPhone|iPad/.test(ua) ? "iOS" : "?");

const L = [];
const out = (s = "") => L.push(s);
const anyWarm = bench.find((r) => r.phase === "warm");
out("# Browser benchmark (Phase 10)");
out();
out(
  "Generated by `js/bench_report.mjs` from `js/bench_browsers.mjs` runs (`data/bench/`). Each run uses the app's own parser " +
    "worker (`createParserWorker` → `transformerBackend.ts`, wink words, MST, gated and labeled phrases, alternatives), " +
    "served by `bench-page/` with the production headers (COOP/COEP) and `/models/*` emulating the R2 route.",
);
out();
out("**Setup**");
out();
out("- Runs (label: browser, OS, logical cores, `navigator.deviceMemory` in GB as reported by the browser):");
for (const b of browsers) {
  const env = bench.find((r) => r.browser === b)?.env ?? {};
  const host = b === "chrome" || b === "safari" ? "development machine (Apple M5 Pro, 48 GB, AC power)" : "client machine (T67)";
  out(`  - \`${b}\`: ${version(env.userAgent ?? "")}, ${os(env.userAgent ?? "")}, ${env.hardwareConcurrency ?? "?"} cores, ${env.deviceMemory ?? "?"} GB; ${host}.`);
}
out("- Owner: Safari and Chrome only for now.");
out(`- Sample: ${anyWarm?.sample_chars} characters of EWT test text (${anyWarm?.sentences} sentences, ${anyWarm?.words} words; \`bench-page/sample.txt\`), budget ${cfg.budget_seconds} s.`);
out(`- Cold load: empty model cache, files from a local server (no network time; see download sizes), then init and self-test. Warm load: a fresh page loading from Cache Storage. Parse: one warm-up, then the median of ${cfg.runs}.`);
out(
  `- Memory: resident memory of the browser's processes sampled every ${cfg.memory_sample_ms} ms from outside, peak minus the idle baseline just before the page opened (Chrome: the test profile's process tree; Safari: the page's new WebContent processes plus GPU and networking process growth; client machines: total working set of the browser's processes from \`bench-page/vm-sampler.ps1\`, so other open tabs count too). It includes the page, worker, wink-nlp, ONNX Runtime's WASM heap, and GPU-process memory, so it is the device's cost, not only the model's.`,
);
out("- Every reported run kept the page focused and visible (one 0.5 s unfocused sample in the VM's ModernBERT run, with no slowdown). Safari throttles unfocused pages: ModernBERT int8 parses rose from 1.4 s to 4–6 s in an earlier, unfocused pass, which was discarded.");
out("- `vm-chrome` (T67): Windows 11 ARM VM in UTM on the development machine, 4 GB RAM, 2 vCPUs, reached through an SSH tunnel (`localhost`, so cross-origin isolation applies). It shows the effect of memory and core count; each vCPU is an M5 Pro core, so its parse times are still faster than a typical low-end laptop. Its memory is Windows' working set of all Chrome processes, not comparable one-to-one with the macOS RSS growth.");
out();
out("## Results");
out();
out("| Model | Browser | Variant (backend) | Cold load (ms) | Warm load (ms) | First parse (ms) | Median parse (ms) | Words/s | Within 5 s | Peak memory, cold / warm (GB) |");
out("|---|---|---|---|---|---|---|---|---|---|");
for (const m of models)
  for (const b of browsers)
    for (const v of cfg.variants) {
      const { cold, warm } = pair(b, m, v);
      if (!warm) continue;
      const wps = Math.round((warm.words / warm.parse_median_ms) * 1000);
      out(
        `| ${m} | ${b} | ${v} (${warm.backend}) | ${ms(cold?.cold_load_ms)} | ${ms(warm.warm_load_ms)} | ${ms(warm.first_parse_ms)} | **${ms(warm.parse_median_ms)}** | ${wps.toLocaleString("en-US")} | ${warm.parse_median_ms <= cfg.budget_seconds * 1000 ? "yes" : "**no**"} | ${gb(cold?.memory?.cold_peak_mb)} / ${gb(warm.memory?.warm_peak_mb)} |`,
      );
    }
out();
out(
  `Sentences with alternatives in the sample: ${anyWarm?.sentences_with_alternatives} of ${anyWarm?.sentences} (DeBERTa; Phase 8 dev: ~19%).`,
);
out();
out("**Download size and time** (the variant's ONNX file; shared tokenizer and config files add 3–11 MB, and ONNX Runtime's WASM 27 MB once; times computed at typical connection speeds, not measured):");
out();
out("| Model | Variant | Size (MB) | At 25 Mbit/s | At 100 Mbit/s |");
out("|---|---|---|---|---|");
for (const m of models)
  for (const v of cfg.variants) {
    const bytes = sizes[m]?.[v];
    if (!bytes) continue;
    out(`| ${m} | ${v} | ${(bytes / 1e6).toFixed(0)} | ${Math.round((bytes * 8) / 25e6)} s | ${Math.round((bytes * 8) / 100e6)} s |`);
  }
out();

const failed = runs.filter((r) => r.mode === "bench" && !r.ok);
if (failed.length) {
  out("**Runs that failed** (the app reported the failure; no result):");
  out();
  out("| Browser | Model | Variant | Phase | Error |");
  out("|---|---|---|---|---|");
  for (const r of failed) out(`| ${r.browser} | ${r.model} | ${r.variant} | ${r.phase ?? "—"} | ${String(r.error).split("\n")[0].replaceAll("|", "\\|")} |`);
  out();
}

out("## Single-threaded WASM (no cross-origin isolation)");
out();
out(
  "Without COOP/COEP headers the page is not cross-origin isolated and ONNX Runtime runs WASM on one thread " +
    "(`bench_browsers.mjs --single-thread`, a separate origin so cached isolated responses are not reused). " +
    "The deployed host sends the headers (T12), so this is the fallback case (headers lost, or a browser without " +
    "SharedArrayBuffer). Memory is not reported: Safari reuses an existing content process here, so the per-page figure is not reliable.",
);
out();
out("| Model | Browser | int8 median parse, 1 thread (ms) | Multi-threaded (ms) | Within 5 s |");
out("|---|---|---|---|---|");
for (const r of stRuns) {
  const mt = pair(r.browser, r.model, "int8").warm?.parse_median_ms;
  const budget = cfg.budget_seconds * 1000;
  const verdict = r.parse_median_ms > budget ? "**no**" : r.parse_median_ms > 0.8 * budget ? "yes (barely)" : "yes";
  out(`| ${r.model} | ${r.browser} | **${ms(r.parse_median_ms)}** | ${ms(mt)} | ${verdict} |`);
}
out();

out("## Cache spike (T31)");
out();
out(
  "The page downloaded each model file like `modelLibrary` will (streamed `fetch` into a Blob), hashed it with one " +
    "`crypto.subtle.digest('SHA-256')` over the whole file, checked it against `labels.json` → `files`, and stored it in the " +
    "`transformers-cache` Cache Storage under its absolute `/models/<model>/<file>` URL. The app's worker then loaded the model; " +
    "the bench server logged every `/models` request during that load.",
);
out();
out("| Browser | Model (variant) | Largest file (MB) | Hash time (ms) | SHA-256 match | Model files re-fetched during load | Other requests during load | Download + hash peak (GB) |");
out("|---|---|---|---|---|---|---|---|");
for (const r of runs.filter((x) => x.mode === "spike" && x.ok)) {
  const big = [...r.files].sort((a, b) => b.bytes - a.bytes)[0];
  const others = r.requests_during_load.filter((p) => !r.model_files_refetched.includes(p)).map((p) => `\`${p.replace(`/models/${r.model}/`, "")}\``);
  out(
    `| ${r.browser} | ${r.model} (${r.variant}) | ${(big.bytes / 1e6).toFixed(0)} | ${Math.round(big.hash_ms)} | ${r.files.every((f) => f.sha256_ok) ? "all" : "**no**"} | ${r.model_files_refetched.length ? r.model_files_refetched.join(", ") : "none"} | ${others.join(", ")} | ${gb(r.memory?.download_hash_peak_mb)} |`,
  );
}
out();
out("Findings:");
out();
out("- **No duplicate download:** Transformers.js 4.3.2 finds files our downloader stored in `transformers-cache` under `/models/<model>/<file>` (it checks that key before fetching). Only `labels.json` (read by our runtime with `fetch`) and ONNX Runtime's WASM (`/models/_ort/…`, cached by Transformers.js in the same cache after the first load) were requested.");
out("- **Whole-file hashing is fine:** `crypto.subtle.digest` on the 302 MB file took ≤ 0.26 s; peak memory while downloading and hashing stayed below the warm parse peak. No streaming hash or file splitting is needed (the file is held once as a Blob and once as an ArrayBuffer while hashing).");
out("- **Private windows:** Chrome's incognito-like Playwright context failed `cache.put` for the 302 MB file (\"Unexpected internal error\"; small quota). Pre-flight should treat a low `storage.estimate()` quota as blocking for model download.");
out("- **ONNX Runtime WASM must be self-hosted:** by default Transformers.js loads it from cdn.jsdelivr.net; the app now sets `wasmPaths` to `/models/_ort/` (`transformerBackend.ts`). The asyncify `.wasm` is 26.9 MB (over Pages' 25 MiB limit), so it ships through R2 with the models.");
out();

out("## Parse times for `catalog.json` (owner, T65)");
out();
out(
  "Seconds per 5,000 characters, warm median; the slowest browser counts. `wasm` = int8 with many threads, `wasm_2core` = the 2-core VM, " +
    "`wasm_1thread` = int8 without cross-origin isolation, `webgpu` = fp16. The app picks the tier that matches the device (`preflight/checks.ts` → `wasmTier`). " +
    "No per-model memory requirement: both models ran in the 4 GB VM, so only the device-wide memory hint (4 GB) warns.",
);
out();
out(`| Model | wasm | wasm_2core | wasm_1thread | webgpu | Peak memory int8 / fp16, max (GB) |`);
out("|---|---|---|---|---|---|");
const performance = {};
const full = browsers.filter((b) => !TWO_CORE_BROWSERS.includes(b));
const slowest = (xs) => {
  const v = xs.filter((x) => typeof x === "number");
  return v.length ? Math.round(Math.max(...v)) / 1000 : undefined;
};
for (const m of models) {
  const median = (b, v) => pair(b, m, v).warm?.parse_median_ms;
  const t = {
    wasm: slowest(full.map((b) => median(b, "int8"))),
    wasm_2core: slowest(TWO_CORE_BROWSERS.map((b) => median(b, "int8"))),
    wasm_1thread: slowest(stRuns.filter((r) => r.model === m).map((r) => r.parse_median_ms)),
    webgpu: slowest(full.map((b) => median(b, "fp16"))),
  };
  performance[m] = Object.fromEntries(Object.entries(t).filter(([, v]) => v !== undefined));
  const peak = (v) => Math.max(...browsers.map((b) => pair(b, m, v).warm?.memory?.warm_peak_mb ?? 0)) / 1024;
  const cell = (v) => (v === undefined ? "—" : v.toFixed(3));
  out(`| ${m} | ${cell(t.wasm)} | ${cell(t.wasm_2core)} | ${cell(t.wasm_1thread)} | ${cell(t.webgpu)} | ${peak("int8").toFixed(2)} / ${peak("fp16").toFixed(2)} |`);
}
out();
out("## Lower-end device (T67): findings");
out();
out("- **4 GB is enough for int8:** both models loaded and parsed in the 4 GB VM without a crash (Chrome's processes grew by at most 0.9 GB).");
out("- **ModernBERT int8 misses the budget on 2 cores:** 5.2 s median (DeBERTa int8: 1.3 s). On a real low-end laptop (slower cores) it will be slower still, so ModernBERT should not be recommended for devices without fp16 WebGPU.");
out("- **WebGPU without fp16:** the VM exposes WebGPU, but its adapter lacks the `shader-f16` feature, so the fp16 variants fail to load (\"The device (webgpu) does not support fp16\"; status `failed: unsupported`). Pre-flight must check `shader-f16`, not only `navigator.gpu`, and choose int8 (WASM) on such devices.");
out();
out("## Not measured yet");
out();
out("- A physical low-end device (slower cores than the VM's), and a phone.");
out("- Firefox and Edge (owner: Safari and Chrome only for now).");
out("- Real network download time (sizes and estimates above).");
out();
writeFileSync(join(TRAINING, "reports", "benchmark.md"), L.join("\n"));
writeFileSync(join(BENCH, "catalog_performance.json"), JSON.stringify(performance, null, 2) + "\n");
console.log("-> reports/benchmark.md", performance);
