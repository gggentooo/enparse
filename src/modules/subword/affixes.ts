export const PREFIXES: readonly Affix[] = AFFIXES.filter((a) => a.kind === "prefix");
export const SUFFIXES: readonly Affix[] = AFFIXES.filter((a) => a.kind === "suffix");

/** All spellings of the affixes of one kind, longest first (longest-match stripping). */
export function spellings(kind: Affix["kind"]): Array<{ text: string; affix: Affix }> {
  return (kind === "prefix" ? PREFIXES : SUFFIXES)
    .flatMap((a) => [a.form, ...a.variants].map((text) => ({ text, affix: a })))
    .sort((x, y) => y.text.length - x.text.length || x.text.localeCompare(y.text));
}
